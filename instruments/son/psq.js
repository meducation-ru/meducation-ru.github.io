// доля «да» среди отвеченных; «не знаю» не входит в знаменатель; в пунктах 17-22 «довольно сильно» и «точно» = да
CUSTOM.psq = (a, inst) => {
  let yes = 0, n = 0;
  for (const it of inst.items) { const v = a[it.id]; if (v < 0) continue; n++; yes += it.likert ? (v >= 2 ? 1 : 0) : v; }
  if (!n) return { total: 0, band: { label: "Нельзя посчитать: на все вопросы ответ «не знаю»", source: src } };
  const total = Math.round(yes / n * 100) / 100;
  return { total, band: { label: yes / n >= 0.33 ? "Порог 0,33 и выше: по Chervin указывает на вероятные нарушения дыхания во сне" : "Ниже порога 0,33", source: src } };
};
